#!/usr/bin/env python3
"""BF7: цветокор снимков веб-камеры — полный кадр, без обрезки.

Хозяин (2026-09-23): смотреть полный кадр, а чинить только цвет.

Что выяснилось опытом (таблица цветных полос на телефоне, 2026-09-23):
у камеры скрытые от настроек автоэкспозиция и автобаланс белого, и оба
подстраиваются под сцену. На яркой пёстрой таблице она зеленит (серый 128 →
55,126,101), а тёмный интерфейс phosh снимает почти нейтрально. Поэтому
постоянная поправка не годится ни в каком виде: кривые или коэффициенты
каналов, снятые по таблице, красят тёмный интерфейс в розовый (проверено), а
матрица 3×3 на полосах вне подбора только хуже. На тёмном экране яркие
значки к тому же пересвечены ещё в датчике — brightness/contrast/gamma
действуют после датчика и это не лечат (проверено на 5 наборах).

Остаётся поправка по самому кадру: уровни каждого канала — самое тёмное к
чёрному, самое светлое к белому. Не зависит ни от экспозиции, ни от баланса
камеры и ничего не портит; сдвиг средних тонов на пёстрых сценах не лечит.

    bf7-glaz-cvet.py ispravit КАДР.png ВЫХОД.png [--stoya]
    bf7-glaz-cvet.py tablica ВЫХОД.png      — таблица полос для проверок
    bf7-glaz-cvet.py podsvetka КАДР.png     — нужно ли приглушить экран (темно)

--stoya — повернуть на четверть: телефон лежит боком, вырез справа; после
поворота верх телефона смотрит вверх. Кадр остаётся полным.
"""
import sys

import numpy as np
from PIL import Image, ImageDraw

CVETA = [(255, 255, 255), (0, 0, 0), (64, 64, 64), (128, 128, 128), (192, 192, 192),
         (255, 0, 0), (0, 255, 0), (0, 0, 255), (0, 255, 255), (255, 0, 255), (255, 255, 0),
         (255, 128, 0), (200, 150, 120), (128, 0, 0), (0, 128, 0), (0, 0, 128)]
NIZH, VERH = 0.5, 99.8          # процентили для чёрной и белой точки


def tablica(vyhod):
    im = Image.new("RGB", (720, 1612))
    d = ImageDraw.Draw(im)
    h = 1612 / len(CVETA)
    for i, c in enumerate(CVETA):
        d.rectangle((0, round(i * h), 719, round((i + 1) * h) - 1), fill=c)
    im.save(vyhod)


def ispravit(put_kadra, vyhod, stoya):
    a = np.asarray(Image.open(put_kadra).convert("RGB"), float)
    tochki = a.reshape(-1, 3)
    lo = np.percentile(tochki, NIZH, axis=0)
    hi = np.percentile(tochki, VERH, axis=0)
    b = (a - lo) / np.maximum(hi - lo, 1.0) * 255.0
    im = Image.fromarray(np.clip(b, 0, 255).astype(np.uint8))
    if stoya:
        im = im.rotate(90, expand=True)
    im.save(vyhod)


def podsvetka(put_kadra):
    """Сколько поставить подсветку телефона на время снимка ('' — не трогать).

    В тёмной комнате автоэкспозиция камеры упирается в предел, и яркие
    элементы экрана пересвечиваются ещё в датчике — никакие настройки камеры
    это не лечат. Помогает только приглушить сам экран: при подсветке 10 из
    255 значки phosh видны целиком и в своих цветах (проверено 2026-09-23,
    свет выключен). Признаки темноты: края кадра (стол вне телефона) темнее
    60, и почти белых точек больше 1% — это и есть пересвеченные значки. На
    свету края светлые; яркая таблица во весь экран даёт тёмные края, но
    почти без белых точек — её не трогаем.
    """
    a = np.asarray(Image.open(put_kadra).convert("RGB"), float)
    yark = a.mean(2)
    kraya = np.concatenate([yark[:60].ravel(), yark[-60:].ravel()]).mean()
    belye = (a.min(2) >= 225).mean() * 100
    return "10" if kraya < 60 and belye > 1.0 else ""


def main(a):
    if len(a) >= 2 and a[0] == "podsvetka":
        print(podsvetka(a[1]))
    elif len(a) >= 3 and a[0] == "ispravit":
        ispravit(a[1], a[2], "--stoya" in a[3:])
    elif len(a) >= 2 and a[0] == "tablica":
        tablica(a[1])
    else:
        print(__doc__.strip().split("\n\n")[4], file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
