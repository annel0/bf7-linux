#!/bin/sh
# BF7: засыпать только с погашенным трактом экрана.
#
# Ставится в /usr/lib/systemd/system-sleep/ — systemd зовёт его перед сном
# («pre») и после («post»). 2026-09-24: сон при горящем экране ломал очередь
# команд дисплея (CMDQ «SW timeout» прямо во время засыпания и дальше без
# конца), обработчик таймаута держал процессор, через ~25 с ядро ловило
# зависание RCU — и всё, что ждёт synchronize_rcu (сеть, закрытие tty моста
# модема), вставало. Первой жертвой оказывалась перезагрузка: она висела до
# сброса сторожем. С погашенным экраном — 0 таймаутов и 0 зависаний.
#
# Обычно телефон и так засыпает с тёмным экраном (gsd-power усыпляет по
# простою уже после гашения), но `systemctl suspend` при горящем экране —
# вручную или из сценария — попадал в ошибку. Гасит экран phoc по нажатию
# кнопки питания (bf7-knopka), как если бы человек нажал её сам.
#
# rtcwake пишет в /sys/power/state мимо systemd: для опытов с ним экран гасить
# заранее.
[ "$1" = pre ] || exit 0

# Вывод ШИМ подсветки (GPIO43, функция 1 — DISP_PWM) перед сном — в обычный
# GPIO с «0». В глубоком сне (deep) дисплейный блок обесточен, и вывод ШИМ
# оставался в состоянии, которое микросхема подсветки читает как «полная
# яркость»: экран светился пустым светом, ~377 мА во сне (2026-09-24, замер
# кулонометром; камера — экран светится, с этой правкой тёмный). Вернёт
# функцию ШИМ bf7-posle-sna по метке /run/bf7-gpio43-shim.
pogasit_podsvetku() {
	g=/sys/devices/platform/pinctrl@10005000/mt_gpio
	[ -e "$g" ] || return 0
	chmod 644 "$g" 2>/dev/null
	grep -q '^043: 1' "$g" || return 0
	echo "mode 43 0" > "$g" && echo "out 43 0" > "$g" && touch /run/bf7-gpio43-shim
}

ekran_gorit() {
	grep -A2 '^crtc' /sys/kernel/debug/dri/1/state 2>/dev/null | grep -q 'active=1'
}

if ekran_gorit; then
	/usr/local/bin/bf7-knopka >/dev/null 2>&1
	i=0
	while [ $i -lt 30 ] && ekran_gorit; do
		sleep 0.1
		i=$((i + 1))
	done
	ekran_gorit && echo "bf7-ekran-pered-snom: экран не погас за 3 с, сон при горящем экране" > /dev/kmsg
fi
# Подсветку гасим только при погашенном экране: иначе он потухнет посреди работы.
ekran_gorit || pogasit_podsvetku
exit 0
