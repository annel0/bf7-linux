#!/bin/sh
# BF7: запуск браузера GNOME Web.
#
# Зачем отдельный запуск. Процесс отрисовки WebKit живёт в песочнице
# bubblewrap, а она прячет от него /vendor, /apex и /usr/local — то есть весь
# наш слой EGL. Без них он падает по кругу, и окно остаётся пустым. Песочницу
# приходится снимать, и WebKit честно требует называть переменную длинно.
#
# Насколько это уступка. В нашем случае небольшая: сеанс и так идёт от root,
# так что песочница защищает скорее от чужого сайта, чем от самого браузера.
# Но снимаем её только здесь, для одного приложения, а не для всего сеанса.
# Если понадобится строгость — убрать строку и вернуться к вопросу.
#
# Отдельно: вторая половина починки живёт в libhybris, см. заплатку
# hybris/bf7-patches/libhybris-bf7.patch. Без неё браузер не доживал даже до
# песочницы: WebKit просит второй дисплей EGL через платформу GBM, а модуль
# оконной системы в процессе один, и запрос проваливался с
# «Could not create GBM EGL display: EGL_NOT_INITIALIZED».
set -u

export WEBKIT_DISABLE_SANDBOX_THIS_IS_DANGEROUS=1

# Путь DMABuf (страница из процесса отрисовки уходит в окно буфером dma-buf,
# без копий) работает штатно с 2026-09-25: до этого страницы были серыми,
# потому что libhybris не отдавал через glvnd eglCreateSync и соседей из
# ядра EGL 1.5, и обмен кадрами с fence застревал после первого. Подпорки
# WEBKIT_DISABLE_DMABUF_RENDERER / WEBKIT_DMABUF_RENDERER_DISABLE_GBM больше
# не нужны: обе рисуют через общую память (glReadPixels каждый кадр).

# GStreamer для <video>: GLES вместо несуществующего настольного GL и
# аппаратный H.264. В сеансе phosh это уже задано (bf7-phosh.service);
# здесь — для запуска браузера из ssh или другого окружения.
export GST_GL_API="${GST_GL_API:-gles2}"
export GST_PLUGIN_FEATURE_RANK="${GST_PLUGIN_FEATURE_RANK:-vah264dec:MAX}"

exec /usr/bin/epiphany "$@"
