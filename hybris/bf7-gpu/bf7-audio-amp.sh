#!/bin/sh
# BF7: включение внешнего усилителя звука.
#
# История вопроса длинная, поэтому коротко о сути. Вывод включения усилителя —
# линия 151 на gpiochip0 (mt_soc_dl1_pcm@11220000/extamp_gpio в дереве
# устройств). Дальше возможны два состояния, и какое сложится — зависит от
# порядка запуска:
#
#   1. Линию держит драйвер (в gpioinfo она подписана fs1512_extamp_gpio).
#      Тогда ею управляет ключ микшера Ext_Speaker_Amp_Switch, причём только
#      при СМЕНЕ значения: повторная единица ничего не делает.
#   2. Линия свободна (unused). Ключ микшера тогда ни на что не влияет, и
#      держать вывод высоким приходится самим.
#
# Драйверу мешать нельзя: если перехватить линию раньше него, он её не получит
# и ключ останется мёртвым. Поэтому порядок такой: сперва пробуем ключ, и
# только если вывод не поднялся — берём линию себе.
#
# Скрипт не завершается, пока держит линию: отпустить её значит замолчать.
set -u

CHIP=gpiochip0
LINE=151
DBG=/sys/devices/platform/pinctrl@10005000/mt_gpio

level() {
	grep -E "^${LINE}:" "$DBG" 2>/dev/null | awk '{print $2}' | cut -c3
}

# Путь первый: ключ микшера, через ноль.
amixer -c 0 cset name=Ext_Speaker_Amp_Switch 0 >/dev/null 2>&1 || true
sleep 1
amixer -c 0 cset name=Ext_Speaker_Amp_Switch 1 >/dev/null 2>&1 || true
sleep 1

if [ "$(level)" = 1 ]; then
	echo "bf7-audio-amp: усилитель включён ключом микшера, линию ведёт драйвер"
	# Держать нечего, но выходить нельзя: служба типа exec должна жить.
	while :; do sleep 3600; done
fi

echo "bf7-audio-amp: ключ не поднял вывод, беру линию $LINE себе" >&2
exec gpioset --mode=signal "$CHIP" "${LINE}=1"
