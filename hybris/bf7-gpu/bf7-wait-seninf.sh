#!/bin/sh
# BF7: дождаться, пока приёмник камеры настроен.
#
# Зачем. bf7-camd стоит в очереди за bf7-camera.service, но та Type=simple:
# systemd считает её запущенной, как только процесс разветвился, а приёмник к
# этому моменту ещё не настроен. Демон видел «приёмник молчит», выходил с
# единицей, и только перезапуск через две секунды заставал всё готовым. В
# журнале это выглядело как упавшая при загрузке служба — то есть как шум,
# за которым легко проглядеть настоящую поломку.
#
# Как узнаём готовность. bf7-seninf-up, настроив приёмник, держит открытыми
# /dev/camera-isp и /dev/kd_camera_hw. Проверяем именно это. Процесс берём
# у systemd — это главный процесс bf7-camera.service. Раньше его искали
# обходом /proc с внешним readlink на каждый процесс: при загрузке это сотни
# порождений на шаг (около 2 с на обход) — столько и стоял bf7-camd.
#
# Имена переменных только латиницей: /bin/sh кириллические не принимает.
set -u

deadline=${1:-40}
i=0

while [ "$i" -lt "$deadline" ]; do
	pid=$(systemctl show -p MainPID --value bf7-camera.service 2>/dev/null)
	if [ -n "$pid" ] && [ "$pid" != 0 ]; then
		p=/proc/$pid
		for fd in "$p"/fd/*; do
			if [ "$fd" -ef /dev/camera-isp ]; then
				# Приёмник настроен. Секунда на то, чтобы поток устоялся:
				# первый кадр после настройки приходит не мгновенно.
				sleep 1
				echo "bf7-wait-seninf: приёмник готов через ${i} с"
				exit 0
			fi
		done
	fi
	i=$((i + 1))
	sleep 1
done

echo "bf7-wait-seninf: за ${deadline} с приёмник не поднялся, пробуем как есть" >&2
exit 0
