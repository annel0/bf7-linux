#!/bin/sh
# BF7: то, что композитор запускает внутри телефонного сеанса.
#
# Это gnome-session с описанием phosh.session, а не одна оболочка. Так
# поднимается всё, что она ждёт рядом с собой: службы яркости, звука,
# мультимедийных клавиш, времени, а заодно имя org.gnome.SessionManager, на
# отсутствие которого phosh жаловалась. Экранная клавиатура (sm.puri.OSK0)
# тоже входит в обязательные составляющие сеанса, поэтому руками её больше
# запускать не нужно.
#
# Оболочка поднимается разблокированной. Это задано в нашем описании
# /usr/local/share/applications/sm.puri.Phosh.desktop, которое перекрывает
# системное: её экран блокировки на сочетании phoc 0.24 с wlroots 0.15 глотает
# касания. Проверено, что дело именно в нём, а не в нашем стеке: голое окно
# GTK3 под тем же композитором отвечает на касания и спустя три минуты работы,
# и после пяти жестов подряд.
# Звук здесь не запускаем. Раньше тут стояли pipewire, wireplumber и
# pipewire-pulse, но их в системе давно нет: wireplumber ронял ядро перебором
# устройств звуковой карты и удалён, а звук идёт через свой PulseAudio
# (bf7-pulse.service). Строки лишь сыпали «not found» в журнал и стоили двух
# секунд sleep на каждом старте сеанса — убраны 2026-09-22.
set -e


# Примирение яркости с gsd-power.
#
# У подсветки два хозяина, и они умеют расходиться. gsd-power узнаёт «сколько
# сейчас процентов», прочитав железо при своём запуске. А запускается он уже
# внутри сеанса — к этому времени bf7-blank мог увидеть погашенный вывод и
# честно поставить ноль. gsd принимает этот ноль за выбор хозяина и дальше
# держит экран еле живым: снаружи это выглядит как «экран почти не светится»,
# и по снимку grim такого не увидеть вовсе — он берёт кадр до матрицы.
# Поймано камерой: подсветка стояла на 12 из 255.
#
# Поэтому один раз за сеанс сверяем его мнение с здравым смыслом. Трогаем
# только совсем уж глухие значения, ниже двадцатой доли: если хозяин сам
# приглушил экран до читаемого уровня, это его право.
bf7_yarkost() {
    put=org.gnome.SettingsDaemon.Power
    tochka=/org/gnome/SettingsDaemon/Power
    lico=org.gnome.SettingsDaemon.Power.Screen
    teper=""

    # Ждём gsd-power, но не бесконечно: у любого ожидания должен быть предел,
    # иначе одна невзлетевшая служба подвешивает всё вокруг себя.
    popytka=0
    while [ "$popytka" -lt 40 ]; do
        teper=$(busctl --user get-property "$put" "$tochka" "$lico" \
                Brightness 2>/dev/null | awk '{print $2}')
        case "$teper" in
            ''|*[!0-9]*) teper="";;
            *) break;;
        esac
        sleep 1
        popytka=$((popytka + 1))
    done

    [ -n "$teper" ] || return 0
    if [ "$teper" -lt 20 ]; then
        busctl --user set-property "$put" "$tochka" "$lico" \
            Brightness i 55 >/dev/null 2>&1
        echo "bf7: яркость была $teper%, поднял до 55%" >&2
    fi
}

# Через подоболочку (двойной fork): после exec ниже фоновое задание стало бы
# потомком gnome-session, а она чужих детей не собирает — по зомби
# bf7-phosh-session на каждый запуск сеанса (замечено 2026-09-30). Так его
# подбирает PID 1.
( bf7_yarkost & )

# Ночной свет: слушает gsd-color по сеансовой шине и пишет таблицу в блок
# гаммы тракта экрана. Уходит сам, когда закрывается шина сеанса.
[ -x /usr/local/bin/bf7-nochnoj-svet ] && ( /usr/local/bin/bf7-nochnoj-svet & )

exec gnome-session --disable-acceleration-check --session=phosh --builtin
