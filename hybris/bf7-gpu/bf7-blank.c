/*
 * BF7: гашение экрана по кнопке питания, отдельно от композитора.
 *
 * Прежде эта работа жила внутри нашего Qt-композитора (класс Подсветка в
 * gui/main.cpp). Для телефонного сеанса это не годится: там композитор чужой
 * (phoc), а трогать его исходники не хочется. Демон ни от кого не зависит —
 * читает кнопку прямо с устройства ввода и правит два узла в /sys.
 *
 * Что делает короткое нажатие:
 *   1. гасит или зажигает подсветку /sys/class/leds/lcd-backlight/brightness;
 *   2. усыпляет или будит тачскрин, запрещая его прерывание;
 *   3. гасит подсветку следом за выводом.
 *
 * Третье появилось 2026-09-22 по замеру. Когда экран гаснет по простою,
 * композитор выключает вывод на уровне KMS, а подсветка остаётся гореть:
 *
 *     соединитель=disabled подсветка=53 светодиод=53 bl_power=0
 *
 * Панель ничего не показывает, а батарея тратится. Поэтому следим за
 * /sys/class/drm/card1-DSI-1/enabled и ведём подсветку за ним: гаснет вывод —
 * запоминаем яркость и ставим ноль, включается — возвращаем.
 *
 * Второе важно: без него погашенный телефон в кармане продолжает получать
 * касания и тратить заряд, а замер показал 175 мА разницы. Заодно это надёжнее
 * фильтра событий в композиторе — тот глотал касания уже после того, как
 * контроллер их обработал.
 *
 * Долгое нажатие не трогаем: им занимается systemd-logind
 * (HandlePowerKeyLongPress=poweroff в нашей вставке bf7-power-key.conf).
 *
 * Никогда не писать в sysfs/reset тачскрина: прошивка у TD4160 загружается
 * хозяином, и сброс роняет его в загрузчик ПЗУ до перезагрузки.
 *
 * Сборка:  gcc -O2 -o bf7-blank bf7-blank.c
 */
#define _GNU_SOURCE
#include <linux/input.h>
#include <sys/ioctl.h>
#include <fcntl.h>
#include <unistd.h>
#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#include <dirent.h>
#include <poll.h>
#include <errno.h>

/*
 * Яркость правим через устройство класса backlight, если оно есть: его
 * объявляет наш модуль bf7_backlight, и им же пользуется gsd-power, а через
 * него ползунок в оболочке. Писать напрямую в светодиод, когда к нему привязан
 * триггер, бессмысленно — следующее обновление подсветки затрёт наше значение.
 * Прямой путь оставлен запасным: модуля может не оказаться.
 */
#define ПОДСВЕТКА_НОВАЯ "/sys/class/backlight/bf7-backlight/brightness"
#define ПОДСВЕТКА_СТАРАЯ "/sys/class/leds/lcd-backlight/brightness"
#define ТАЧ "/sys/devices/platform/11012000.spi2/spi_master/spi2/spi2.0/" \
	    "synaptics_tcm.0/synaptics_tcm/irq_en"

/* Состояние вывода: "enabled" или "disabled" с переводом строки. */
#define СОЕДИНИТЕЛЬ "/sys/class/drm/card1-DSI-1/enabled"

static const char *подсветка(void)
{
	static const char *выбор;

	if (!выбор) {
		int fd = open(ПОДСВЕТКА_НОВАЯ, O_WRONLY);

		if (fd >= 0) {
			close(fd);
			выбор = ПОДСВЕТКА_НОВАЯ;
		} else {
			выбор = ПОДСВЕТКА_СТАРАЯ;
		}
		fprintf(stderr, "bf7-blank: яркость через %s\n", выбор);
	}
	return выбор;
}

static int записать(const char *путь, const char *знач)
{
	int fd = open(путь, O_WRONLY);
	if (fd < 0)
		return -1;
	ssize_t n = write(fd, знач, strlen(знач));
	close(fd);
	return n > 0 ? 0 : -1;
}

static int прочитать_число(const char *путь)
{
	char буф[32] = {0};
	int fd = open(путь, O_RDONLY);
	if (fd < 0)
		return -1;
	read(fd, буф, sizeof буф - 1);
	close(fd);
	return atoi(буф);
}

/* Кнопка питания живёт на mtk-pmic-keys; номер устройства между сборками
   ядра меняется, поэтому ищем по имени, а не по номеру. */
/*
 * 1 — вывод включён, 0 — выключен, -1 — не смогли прочитать. Файла может не
 * быть, если номер карты или имя соединителя когда-нибудь изменятся; в этом
 * случае просто не вмешиваемся.
 */
static int вывод_включён(void)
{
	char буфер[32];
	int fd = open(СОЕДИНИТЕЛЬ, O_RDONLY);
	ssize_t взято;

	if (fd < 0)
		return -1;

	взято = read(fd, буфер, sizeof буфер - 1);
	close(fd);
	if (взято <= 0)
		return -1;

	буфер[взято] = 0;
	return strncmp(буфер, "enabled", 7) == 0;
}

static int найти_кнопку(void)
{
	DIR *d = opendir("/dev/input");
	if (!d)
		return -1;
	struct dirent *з;
	int найден = -1;
	while ((з = readdir(d))) {
		if (strncmp(з->d_name, "event", 5))
			continue;
		char путь[64];
		snprintf(путь, sizeof путь, "/dev/input/%s", з->d_name);
		int fd = open(путь, O_RDONLY);
		if (fd < 0)
			continue;
		char имя[128] = {0};
		ioctl(fd, EVIOCGNAME(sizeof имя), имя);
		if (strstr(имя, "pmic-keys") || strstr(имя, "mtk-kpd")) {
			/* Проверяем, что это именно кнопка питания. */
			unsigned long биты[(KEY_MAX + 8) / (8 * sizeof(long))];
			memset(биты, 0, sizeof биты);
			ioctl(fd, EVIOCGBIT(EV_KEY, sizeof биты), биты);
			int есть = биты[KEY_POWER / (8 * sizeof(long))] >>
				   (KEY_POWER % (8 * sizeof(long))) & 1;
			if (есть) {
				fprintf(stderr, "bf7-blank: кнопка на %s (%s)\n", путь, имя);
				найден = fd;
				break;
			}
		}
		close(fd);
	}
	closedir(d);
	return найден;
}

int main(void)
{
	int fd = найти_кнопку();
	if (fd < 0) {
		fprintf(stderr, "bf7-blank: кнопка питания не найдена\n");
		return 1;
	}

	/* Тач мог остаться усыплённым с прошлого раза — будим безусловно. */
	записать(ТАЧ, "1\n");

	int яркость = прочитать_число(подсветка());
	if (яркость <= 0)
		яркость = 140;
	int погашен = 0;
	setvbuf(stderr, NULL, _IOLBF, 0);

	/*
	 * Ждём одновременно двух вещей: нажатия кнопки и смены состояния вывода.
	 * Состояние соединителя в sysfs не умеет будить poll, поэтому опрашиваем
	 * его по таймауту. Полсекунды достаточно: дольше подсветка гореть впустую
	 * не будет, а нагрузки от одного чтения файла нет никакой.
	 */
	int вывод_был = вывод_включён();
	int яркость_до_гашения = яркость;

	for (;;) {
		struct pollfd ожидание = { .fd = fd, .events = POLLIN };
		int готово = poll(&ожидание, 1, 500);
		struct input_event e;

		if (готово < 0) {
			if (errno == EINTR)
				continue;
			break;
		}

		if (готово == 0 || !(ожидание.revents & POLLIN)) {
			int сейчас = вывод_включён();

			/*
			 * Пока вывод выключен, держим ноль. Одного раза мало: gsd-power
			 * приглушает подсветку уже после того, как гасит вывод, и
			 * оставляет её на двойке — панель тёмная, а светодиод всё же
			 * питается. Пишем только когда есть что гасить, так что в покое
			 * это ровно одно чтение файла в полсекунды.
			 */
			if (сейчас == 0 && прочитать_число(подсветка()) > 0)
				записать(подсветка(), "0\n");

			/*
			 * Пока вывод включён, запоминаем последнюю настоящую яркость.
			 * Порог нужен: перед гашением gsd-power приглушает подсветку до
			 * двойки, и если запомнить её, то после пробуждения экран вернётся
			 * еле живым. Всё, что ниже порога, считаем приглушением, а не
			 * выбором хозяина.
			 */
			if (сейчас == 1) {
				int теперь = прочитать_число(подсветка());

				if (теперь >= 5)
					яркость_до_гашения = теперь;
			}

			if (сейчас >= 0 && вывод_был >= 0 && сейчас != вывод_был) {
				if (!сейчас) {
					записать(подсветка(), "0\n");
					fprintf(stderr, "bf7-blank: вывод выключен, гашу подсветку "
						"(было %d)\n", яркость_до_гашения);
				} else {
					char знач[16];

					snprintf(знач, sizeof знач, "%d\n", яркость_до_гашения);
					записать(подсветка(), знач);
					fprintf(stderr, "bf7-blank: вывод включён, возвращаю "
						"подсветку %d\n", яркость_до_гашения);
				}
			}
			if (сейчас >= 0)
				вывод_был = сейчас;
			continue;
		}

		if (read(fd, &e, sizeof e) != sizeof e)
			break;

		if (e.type != EV_KEY || e.code != KEY_POWER || e.value != 1)
			continue;

		if (погашен) {
			char знач[16];
			snprintf(знач, sizeof знач, "%d\n", яркость);
			записать(подсветка(), знач);
			записать(ТАЧ, "1\n");
			погашен = 0;
			fprintf(stderr, "bf7-blank: экран зажжён (%d)\n", яркость);
		} else {
			int текущая = прочитать_число(подсветка());
			if (текущая > 0)
				яркость = текущая;	/* запоминаем перед гашением */
			записать(ТАЧ, "0\n");
			записать(подсветка(), "0\n");
			погашен = 1;
			fprintf(stderr, "bf7-blank: экран погашен, тач усыплён\n");
		}

		/* Кнопка сама меняет яркость, так что сверяем отметку сразу: иначе
		 * следующий опрос решит, что это вывод погас, и полезет чинить. */
		вывод_был = вывод_включён();
	}

	fprintf(stderr, "bf7-blank: устройство ввода пропало\n");
	return 1;
}
